"""Incident report export (PRD FR-7). Built only from redacted data; final text is redacted again."""
from __future__ import annotations

from .models import Incident, Investigation
from .redact import redact, redact_text
from .safety import SafetyResult
from .timeline import TimelineAnalysis
from .timeutil import utcnow


def report_json(inc: Incident, inv: Investigation, a: TimelineAnalysis, safety: SafetyResult) -> dict:
    return redact({
        "incident": {"reference": inc.reference, "type": inc.incident_type, "severity": inc.severity, "status": inc.status,
                     "transaction_reference": inc.order_id, "capture_id": inc.capture_id, "amount": inc.amount, "currency": inc.currency,
                     "data_origin": "SYNTHETIC TEST DATA" if inc.is_synthetic else "PayPal Sandbox"},
        "severity_explanation": inc.severity_reasons,
        "summary": inv.summary,
        "timeline": [{"time": e.timestamp.isoformat(), "event": e.label, "source": e.source, "kind": e.kind,
                      "state": e.transaction_state, "flags": e.flags, "id": e.id} for e in a.entries],
        "root_cause_analysis": {"root_cause": inv.root_cause, "confidence": inv.confidence, "evidence_confidence": inv.evidence_confidence,
                                "alternative_explanations": inv.alternative_explanations, "missing_information": inv.missing_information,
                                "generated_by": inv.generated_by},
        "supporting_evidence": inv.supporting_evidence,
        "contradictory_evidence": inv.contradictory_evidence,
        "recommended_action": inv.recommended_action,
        "prohibited_actions": inv.prohibited_actions,
        "safety_warnings": safety.warnings,
        "rules_triggered": [r.model_dump() for r in safety.rules_triggered],
        "investigated_at": inv.created_at.isoformat(),
        "report_generated_at": utcnow().isoformat(),
    })


def report_markdown(inc: Incident, inv: Investigation, a: TimelineAnalysis, safety: SafetyResult) -> str:
    r = report_json(inc, inv, a, safety)
    i = r["incident"]
    L = [f"# Incident Report {i['reference']}", "",
         f"**Data origin:** {i['data_origin']}  ",
         f"**Type:** {i['type']}  **Severity:** {i['severity']}  **Status:** {i['status']}  ",
         f"**Transaction reference:** {i['transaction_reference']}  **Amount:** {i['amount']} {i['currency']}  ",
         f"**Investigated at:** {r['investigated_at']}", "",
         "## Summary", r["summary"], "", "## Why this severity"]
    L += [f"- {x}" for x in (inc.severity_reasons or {}).get("reasons", [])] + ["", "_Severity is operational impact, not fraud probability._", ""]
    L += ["## Event timeline"]
    for e in r["timeline"]:
        tag = " _(inferred)_" if e["kind"] == "inferred" else (" _(unverified)_" if e["kind"] == "unverified" else "")
        flags = f" ⚠ {', '.join(e['flags'])}" if e["flags"] else ""
        L.append(f"1. `{e['time']}` {e['event']}{tag}{flags}  `[{e['id'][:12]}]`")
    rca = r["root_cause_analysis"]
    L += ["", "## Root-cause analysis", rca["root_cause"], "", f"**Confidence:** {rca['confidence']} (evidence quality: {rca['evidence_confidence']}; generated by {rca['generated_by']})", ""]
    L += ["### Supporting evidence"] + [f"- `{x['event_id'][:12]}` {x['statement']}" for x in r["supporting_evidence"]] or ["- none"]
    if r["contradictory_evidence"]:
        L += ["", "### Contradictory evidence"] + [f"- `{x['event_id'][:12]}` {x['statement']}" for x in r["contradictory_evidence"]]
    if rca["alternative_explanations"]:
        L += ["", "### Alternative explanations"] + [f"- {x}" for x in rca["alternative_explanations"]]
    if rca["missing_information"]:
        L += ["", "### Missing information"] + [f"- {x}" for x in rca["missing_information"]]
    ra = r["recommended_action"]
    L += ["", "## Recommended action", f"**{ra.get('code')}** - {ra.get('explanation')}", "", "_Any consequential payment operation requires explicit human approval._", "",
          "## Actions that should NOT be taken"] + [f"- **{p['code']}**: {p['reason']}" for p in r["prohibited_actions"]]
    L += ["", "## Safety warnings"] + [f"- {w}" for w in r["safety_warnings"]]
    return redact_text("\n".join(L)) + "\n"
